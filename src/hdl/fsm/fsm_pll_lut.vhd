    upper_fsm: process(current_state,pll_cal_done,pll_a_state,pll_b_state,setup_trigger_in)
    begin
        next_state <= current_state;
        case current_state is
            when IDLE =>
                if(setup_trigger_in = '1') then
                    next_state <= PLL_CAL;
                end if;
            when PLL_CAL =>
                if(pll_cal_done = '1') then
                    next_state <= PLL_SETUP;
                end if;
            when PLL_SETUP => 
                if(pll_a_state = PLL_UNUSED) then
                    next_state <= PLLA_SETUP;
                elsif(pll_b_state = PLL_UNUSED) then
                    next_state <= PLLB_SETUP;
                end if;
            when PLLA_SETUP =>  
                if(pll_a_state = PLL_LOCKED) then
                    next_state <= PLL_WAIT;                   
                end if;
            when PLLB_SETUP => 
                if(pll_b_state = PLL_LOCKED) then
                    next_state <= PLL_WAIT;
                end if;
            when PLL_WAIT =>
                if(pll_a_state = PLL_USED) then
                    next_state <= IDLE;
                elsif(pll_b_state = PLL_USED) then
                    next_state <= IDLE;
                end if;
            when others =>
                next_state <= IDLE;
        end case;
    end process;

    lower_fsm: process(fsm_clk_in)
    begin 
        if(fsm_clk_in'event and fsm_clk_in = '1')then
            if(fsm_rstn_in = '0') then
                current_state   <= IDLE;
                pll_boot_out    <= '0';
            else
                current_state   <= next_state;
                pll_boot_out    <= '1';
                if(current_state /= next_state)then
                    pll_state_change_out <= '1';
                    case(next_state) is
                        when IDLE => 
                            pll_state_out <= "0001";
                        when PLL_CAL => 
                            pll_state_out <= "0010";
                        when PLL_SETUP =>
                            pll_state_out <= "0011";
                        when PLLA_SETUP =>
                            pll_state_out <= "0100";
                        when PLLB_SETUP => 
                            pll_state_out <= "0101";
                        when PLL_SWITCH => 
                            pll_state_out <= "0110";
                        when PLL_WAIT =>
                            pll_state_out <= "0111";
                        when others => 
                            pll_state_out <= "0000";
                    end case;
                else
                    pll_state_change_out <= '0';
                end if;
            end if;
        end if;
    end process;


    pll_cal_proc: process(fsm_clk_in)
    begin
        if(fsm_clk_in'event and fsm_clk_in = '1') then
            if(current_state = IDLE) then
                current_N_div       <= (others => '0');
                reg_an_div          <= (others => '0');
                ftw_scale_factor    <= (others => '0');
                filter_id           <= (others => '0');
                calculation_counter <= (others => '0');
                pll_cal_done       <= '0';
            elsif(current_state = PLL_CAL) then
                calculation_counter <= calculation_counter + '1';
                case(calculation_counter) is
                    when "00001" => 
                        if(trx_in = '1') then
                            case(next_bandwdiwth_in) is
                                when BW_25K | BW_50K |BW_75K | BW_2M | BW_4M | BW_8M =>
                                    for i in freq_table_tx_nrbw_248M'range loop
                                        if (unsigned(next_frequency_in) >= freq_table_tx_nrbw_248M(i).start_freq and unsigned(next_frequency_in) <= freq_table_tx_nrbw_248M(i).stop_freq) then
                                            current_N_div       <= freq_table_tx_nrbw_248M(i).current_N_div;
                                            reg_an_div          <= freq_table_tx_nrbw_248M(i).reg_an_div;
                                            ftw_scale_factor    <= freq_table_tx_nrbw_248M(i).ftw_scale_factor;
                                            filter_id           <= freq_table_tx_nrbw_248M(i).filter_id;
                                        end if;
                                    end loop;
                                when BW_40M => 
                                    for i in freq_table_trx_40M'range loop
                                        if (unsigned(next_frequency_in) >= freq_table_trx_40M(i).start_freq and unsigned(next_frequency_in) <= freq_table_trx_40M(i).stop_freq) then
                                            current_N_div       <= freq_table_trx_40M(i).current_N_div;
                                            reg_an_div          <= freq_table_trx_40M(i).reg_an_div;
                                            ftw_scale_factor    <= freq_table_trx_40M(i).ftw_scale_factor;
                                            filter_id           <= freq_table_trx_40M(i).filter_id;
                                        end if;
                                    end loop;  
                                when others =>
                                    current_N_div       <= (others => '0');
                                    reg_an_div          <= (others => '0');
                                    ftw_scale_factor    <= (others => '0');
                                    filter_id           <= (others => '0');
                            end case;
                        else
                            case(next_bandwdiwth_in) is
                                when BW_25K | BW_50K |BW_75K | BW_2M | BW_4M | BW_8M =>
                                    for i in freq_table_rx_nrbw_248M'range loop
                                        if (unsigned(next_frequency_in) >= freq_table_rx_nrbw_248M(i).start_freq and unsigned(next_frequency_in) <= freq_table_rx_nrbw_248M(i).stop_freq) then
                                            current_N_div       <= freq_table_rx_nrbw_248M(i).current_N_div;
                                            reg_an_div          <= freq_table_rx_nrbw_248M(i).reg_an_div;
                                            ftw_scale_factor    <= freq_table_rx_nrbw_248M(i).ftw_scale_factor;
                                            filter_id           <= freq_table_rx_nrbw_248M(i).filter_id;
                                        end if;
                                    end loop;
                                when BW_40M => 
                                    for i in freq_table_trx_40M'range loop
                                        if (unsigned(next_frequency_in) >= freq_table_trx_40M(i).start_freq and unsigned(next_frequency_in) <= freq_table_trx_40M(i).stop_freq) then
                                            current_N_div       <= freq_table_trx_40M(i).current_N_div;
                                            reg_an_div          <= freq_table_trx_40M(i).reg_an_div;
                                            ftw_scale_factor    <= freq_table_trx_40M(i).ftw_scale_factor;
                                            filter_id           <= freq_table_trx_40M(i).filter_id;
                                        end if;
                                    end loop;  
                                when others =>
                                    current_N_div       <= (others => '0');
                                    reg_an_div          <= (others => '0');
                                    ftw_scale_factor    <= (others => '0');
                                    filter_id           <= (others => '0');
                            end case;
                        end if;
                    when "00010" => 
                        current_dds_ftw <= ftw_scale_factor * next_frequency_in;
                    when "00011" => 
                        target_dds_ftw  <= current_dds_ftw(63 downto 32);
                        pll_cal_done    <= '1';
                    when others => 
                        NULL;
                end case ;   
            end if; 
        end if;
    end process;
    pll_setup_proc: process(fsm_clk_in)
    begin
        if(fsm_clk_in'event and fsm_clk_in = '1') then
            if (current_state = PLL_CAL) then
                pll_csn_out <= "1111";
                pll_a_setup_done    <= '0';
                pll_b_setup_done    <= '0';
            elsif(current_state = PLLA_SETUP)then
                pll_a_nb          <= '0';
                pll_setup_counter <= pll_setup_counter + '1';
                if(pll_setup_counter < x"0010")then
                    pll_command_out <= target_dds_ftw;
                    pll_csn_out     <= "1110"; ----- DDS AD9914 reg
                elsif((pll_setup_counter >= x"0010") and (pll_setup_counter < x"0040")) then
                     pll_command_out <= target_dds_ftw;
                    pll_csn_out     <= "1111"; ----- DDS AD9914 reg
                elsif((pll_setup_counter >= x"0040") and (pll_setup_counter < x"0050")) then
                    pll_command_out <= current_N_div;
                    pll_csn_out     <= "1101"; ----- ADF4150 N_div prog              
                elsif((pll_setup_counter >= x"0050") and (pll_setup_counter < x"0060")) then
                    pll_command_out <= current_N_div;
                    pll_csn_out     <= "1111"; ----- ADF4150 N_div prog
                elsif(pll_setup_counter >= pll_setup_time_in) then
                    pll_a_setup_done    <= '1';
                    pll_a_nb          <= '1';
                end if;
                if(reg_an_div = "10") then
                    pll_lo_a_div2_out <= '1';
                    pll_lo_a_hb_out  <= '1';
                else
                    pll_lo_a_div2_out <= '0';
                    pll_lo_a_hb_out  <= '0';
                end if;
            elsif(current_state = PLLB_SETUP)then
                pll_b_nb          <= '0';
                pll_setup_counter <= pll_setup_counter + '1';
                if(pll_setup_counter < x"0010")then
                    pll_command_out <= target_dds_ftw;
                    pll_csn_out     <= "1011"; ----- DDS AD9914 reg
                elsif((pll_setup_counter >= x"0010") and (pll_setup_counter < x"0040")) then
                     pll_command_out <= target_dds_ftw;
                    pll_csn_out     <= "1111"; ----- DDS AD9914 reg
                elsif((pll_setup_counter >= x"0040") and (pll_setup_counter < x"0050")) then
                    pll_command_out <= current_N_div;
                    pll_csn_out     <= "0111"; ----- ADF4150 N_div prog              
                elsif((pll_setup_counter >= x"0050") and (pll_setup_counter < x"0060")) then
                    pll_command_out <= current_N_div;
                    pll_csn_out     <= "1111"; ----- ADF4150 N_div prog
                elsif(pll_setup_counter >= pll_setup_time_in) then
                    pll_b_setup_done    <= '1';
                    pll_b_nb          <= '1';
                end if;
                if(reg_an_div = "10") then
                    pll_lo_b_div2_out <= '1';
                    pll_lo_b_hb_out  <= '1';
                else
                    pll_lo_b_div2_out <= '0';
                    pll_lo_b_hb_out  <= '0';
                end if;
            else
                pll_setup_counter <= (others => '0');
            end if;
        end if;
    end process;

    pll_switch_proc: process(fsm_clk_in)
    begin
        if(fsm_clk_in'event and fsm_clk_in = '1') then
            if(current_state = IDLE) then
                pll_switching_counter <= (others => '0') ;
                pll_switching_counter_en <= '0';
                pll_a_switch_done <= '0';
                pll_b_switch_done <= '0';
            elsif(current_state = PLL_WAIT) then
                if(pll_transition_trigger_in = '1') then
                     pll_switching_counter_en <= '1';
                end if;
                if(pll_switching_counter_en = '1') then
                     pll_switching_counter <= pll_switching_counter + '1';
                    if(pll_switching_counter >= pll_switching_time_in) then
                        if(pll_a_state = PLL_LOCKED) then
                            pll_a_switch_done <= '1';
                            pll_switching_counter_en <= '0';
                        elsif(pll_b_state = PLL_LOCKED) then
                            pll_b_switch_done <= '1';
                            pll_switching_counter_en <= '0';
                        end if;
                    end if;
                else
                    
                end if;
               
            end if;
        end if;
    end process;
    pll_state_updating_proc: process(fsm_clk_in)
    begin
        if(fsm_clk_in'event and fsm_clk_in = '1') then
            if(fsm_rstn_in = '0') then
                pll_a_state <= PLL_UNUSED;
                pll_b_state <= PLL_UNUSED;
            else
                if(pll_a_setup_done = '1') and (current_state = PLLA_SETUP) then
                    pll_a_state <= PLL_LOCKED;
                elsif(pll_b_setup_done = '1') and (current_state = PLLB_SETUP)then
                    pll_b_state <= PLL_LOCKED;
                elsif(pll_a_switch_done = '1') and (current_state = PLL_WAIT) then
                    pll_a_state <= PLL_USED;
                    pll_b_state <= PLL_UNUSED;
                elsif(pll_b_switch_done = '1')  and (current_state = PLL_WAIT) then
                    pll_a_state <= PLL_UNUSED;
                    pll_b_state <= PLL_USED;
                end if;
            end if;
        end if;
    end process;
